"""Standard Webhooks verification, driven by vectors the Node SDK produced.

``tests/fixtures/webhook_vectors.json`` is generated by
``scripts/gen_webhook_vectors.mjs``, which mirrors
``DevinoSolutions/shorty-sdk/test/webhooks.test.ts`` scenario for scenario and
signs with Node's ``crypto``. Passing these proves cross-implementation
agreement with the TypeScript SDK and the server signer — a Python
implementation that only passes its own self-generated signatures proves
nothing.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import time
from typing import Any

import pytest

from shorty_py import DEFAULT_TOLERANCE_SECONDS, verify_webhook_signature
from tests.conftest import load_fixture

VECTORS = load_fixture("webhook_vectors.json")
CASES = VECTORS["cases"]

SECRET = "whsec_" + base64.b64encode(b"local-signing-secret-24b").decode()
NOW = 1_753_000_000
WEBHOOK_ID = "msg_local"


def sign(secret: str, content: str) -> str:
    key = base64.b64decode(secret.removeprefix("whsec_"))
    return base64.b64encode(hmac.new(key, content.encode(), hashlib.sha256).digest()).decode()


def headers_for(webhook_id: str, timestamp: object, signature: str) -> dict[str, str]:
    return {
        "webhook-id": webhook_id,
        "webhook-timestamp": str(timestamp),
        "webhook-signature": signature,
    }


# ---------------------------------------------------------------------------
# The ported cross-implementation vectors
# ---------------------------------------------------------------------------


def test_the_vector_file_covers_the_typescript_scenario_matrix() -> None:
    assert len(CASES) == 10
    names = {case["name"] for case in CASES}
    assert "rotation: two signatures, receiver still on the old secret" in names
    assert "reserialized JSON body fails (the raw-byte rule)" in names


@pytest.mark.parametrize("case", CASES, ids=[c["name"] for c in CASES])
def test_node_generated_vector(case: dict[str, Any]) -> None:
    result = verify_webhook_signature(
        payload=case["payload"],
        headers=headers_for(case["webhook_id"], case["timestamp"], case["signature_header"]),
        secret=case["secret"],
        tolerance_seconds=case.get("tolerance_seconds", DEFAULT_TOLERANCE_SECONDS),
        now_seconds=case["now_seconds"],
    )
    assert result.valid is case["expected_valid"], case["name"]
    assert result.reason == case.get("expected_reason"), case["name"]


